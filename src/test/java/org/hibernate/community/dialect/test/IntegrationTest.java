    @Test
    @Order(7)
    @Story("Advanced Queries")
    @Description("Validates FileMaker's advanced query behavior:\n" +
                "1. Creates multiple contacts\n" +
                "2. Executes HQL queries\n" +
                "3. Verifies query results\n\n" +
                "Expected:\n" +
                "- Queries should return correct results\n\n" +
                "Limitations:\n" +
                "- No support for subqueries")
    @Severity(SeverityLevel.NORMAL)
    @DisplayName("Advanced Query Features")
    @Issue("HIBERNATE-002")
    @TmsLink("TC-002")
    void testAdvancedQueries() {
        // Create contacts with various fields
        createTestContacts();
        transaction.commit();
        session.clear(); // Clear session to ensure fresh data retrieval
        
        // Test query by company
        Query<Contact> companyQuery = session.createQuery(
            "FROM Contact c WHERE c.company = :company", Contact.class);
        companyQuery.setParameter("company", "Example Corp");
        List<Contact> companyContacts = companyQuery.getResultList();
        assertFalse(companyContacts.isEmpty(), "Should find contacts by company");
        assertTrue(companyContacts.stream().allMatch(c -> "Example Corp".equals(c.getCompany())),
            "All contacts should be from Example Corp");
        
        // Test query by job title
        Query<Contact> jobQuery = session.createQuery(
            "FROM Contact c WHERE c.jobTitle LIKE :pattern", Contact.class);
        jobQuery.setParameter("pattern", "%Developer%");
        List<Contact> developerContacts = jobQuery.getResultList();
        assertFalse(developerContacts.isEmpty(), "Should find contacts by job title");
        assertTrue(developerContacts.stream().allMatch(c -> c.getJobTitle().contains("Developer")),
            "All contacts should have Developer in their title");
        
        // Test complex query with multiple conditions
        Query<Contact> complexQuery = session.createQuery(
            "FROM Contact c WHERE c.company = :company " +
            "AND c.jobTitle LIKE :jobPattern " +
            "AND c.email LIKE :emailPattern", Contact.class);
        complexQuery.setParameter("company", "Example Corp");
        complexQuery.setParameter("jobPattern", "%Developer%");
        complexQuery.setParameter("emailPattern", "%.com");
        
        List<Contact> complexResults = complexQuery.getResultList();
        assertFalse(complexResults.isEmpty(), "Should find contacts with complex query");
        
        // Clean up test data
        transaction = session.beginTransaction();
        for (Contact c : complexResults) {
            session.remove(c);
        }
        transaction.commit();
    }
    
