    @Test
    @Order(8)
    @Story("Transaction Management")
    @Description("Validates FileMaker's transaction management behavior:\n" +
                "1. Creates contact with required fields\n" +
                "2. Updates contact fields\n" +
                "3. Rolls back transaction\n" +
                "4. Verifies no changes\n\n" +
                "Expected:\n" +
                "- No changes should be persisted\n\n" +
                "Limitations:\n" +
                "- No support for nested transactions")
    @Severity(SeverityLevel.CRITICAL)
    @DisplayName("Transaction Rollback")
    @Issue("HIBERNATE-002")
    @TmsLink("TC-002")
    void testTransactionRollback() {
        // Create a contact with all required fields
        Contact contact = new Contact("test@example.com", "tuser", "testpass");
        contact.setFirstName("Test");
        contact.setLastName("User");
        
        session.persist(contact);
        transaction.commit();
        session.clear();
        
        Long contactId = contact.getId();
        
        // Get initial state
        Contact savedContact = session.get(Contact.class, contactId);
        String initialEmail = savedContact.getEmail();
        Integer initialModCount = savedContact.getModificationCount();
        
        // Start new transaction
        transaction = session.beginTransaction();
        
        // Update contact
        savedContact.setEmail("invalid@example.com");
        session.merge(savedContact);
        
        // Rollback transaction
        transaction.rollback();
        session.clear();
        
        // Verify the email wasn't updated
        Contact unchangedContact = session.get(Contact.class, contactId);
        assertEquals(initialEmail, unchangedContact.getEmail(),
            "Email should remain unchanged after rollback");
        assertEquals(initialModCount, unchangedContact.getModificationCount(),
            "Modification count should remain unchanged after rollback");
        
        // Clean up
        transaction = session.beginTransaction();
        session.remove(unchangedContact);
        transaction.commit();
    }
    
    @Test
    @Order(9)
    @Story("Batch Operations")
    @Description("Validates FileMaker's batch operation behavior:\n" +
                "1. Creates multiple contacts\n" +
                "2. Persists contacts in batch\n" +
                "3. Verifies batch insert\n\n" +
                "Expected:\n" +
                "- All contacts should be inserted\n\n" +
                "Limitations:\n" +
                "- No support for batch updates or deletes")
    @Severity(SeverityLevel.NORMAL)
    @DisplayName("Batch Operations")
    @Issue("HIBERNATE-002")
    @TmsLink("TC-002")
    void testBatchOperations() {
        // Create multiple contacts in batch
        for (int i = 1; i <= 5; i++) {
            Contact contact = new Contact("batch" + i + "@example.com", "buser" + i, "batch123");
            // Additional fields
            contact.setFirstName("Batch");
            contact.setLastName("User " + i);
            contact.setCompany("Batch Corp");
            contact.setJobTitle("Batch Tester " + i);
            
            session.persist(contact);
            
            if (i % 3 == 0) { // Flush every 3 records
                session.flush();
                session.clear();
            }
        }
        
        transaction.commit();
        session.clear();
        
        // Query to verify batch insert
        Query<Long> countQuery = session.createQuery(
            "SELECT COUNT(c) FROM Contact c WHERE c.email LIKE :pattern",
            Long.class
        );
        countQuery.setParameter("pattern", "batch%");
        
        Long count = countQuery.getSingleResult();
        assertEquals(5L, count, "Should have inserted 5 batch contacts");
        
        // Clean up batch records
        transaction = session.beginTransaction();
        Query<?> deleteQuery = session.createQuery(
            "DELETE FROM Contact c WHERE c.email LIKE :pattern"
        );
        deleteQuery.setParameter("pattern", "batch%");
        deleteQuery.executeUpdate();
        transaction.commit();
    }
